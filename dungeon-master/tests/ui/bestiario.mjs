import { lanzar, fixture, MOCK, salida, paginaDe } from "./_comun.mjs";
import { readFileSync } from "node:fs";
const S = await paginaDe();
const partida = JSON.parse(readFileSync(fixture("partida-codice.json"), "utf8"));
for (const [w, h, n] of [[1280, 900, "escritorio"], [390, 844, "movil"]]) {
  const b = await lanzar();
  const pg = await b.newPage({ viewport: { width: w, height: h } });
  const errs = []; pg.on("pageerror", (e) => errs.push(e.message));
  await pg.addInitScript({ path: MOCK });
  await pg.goto("file://" + S + "/mesa-de-velmora.html"); await pg.waitForTimeout(800);
  await pg.click("#form-tutorial button[type=submit]").catch(() => {}); await pg.fill("#nombre", "Ana"); await pg.click("#form-nombre button"); await pg.waitForTimeout(500);
  const abrir = async () => { if (w < 600) await pg.evaluate(() => document.getElementById("ver-bestiario").click()); else await pg.click("#ver-bestiario"); await pg.waitForTimeout(300); };
  await abrir();
  const n0 = await pg.locator("#bestiario-lista details").count();
  const ocultos0 = await pg.textContent("#bestiario-ocultos");
  console.log(n, "· sin partida: entradas", n0, "·", ocultos0.slice(0, 60));
  await pg.click("#cerrar-bestiario");
  await pg.evaluate((p) => window.__db.doc("mesa/estado").set({ partida: p, actualizado: 5, cronica: "" }), partida); await pg.waitForTimeout(1500);
  const insignia = await pg.evaluate(() => !document.getElementById("bestiario-nuevo").hidden);
  await abrir();
  const n1 = await pg.locator("#bestiario-lista details").count();
  const wen = pg.locator('#bestiario-lista details[data-nombre="Wendigo"]');
  await wen.locator("summary").click(); await pg.waitForTimeout(200);
  const cuerpoW = (await wen.locator(".cuerpo").innerText()).replace(/\n+/g, " | ").slice(0, 200);
  const ghul = pg.locator('#bestiario-lista details[data-nombre="Ghul de las fosas"]'); await ghul.locator("summary").click();
  const bloqueadas = await ghul.locator(".bloqueada").count();
  const y = await pg.locator('#bestiario-lista details[data-nombre^="Ysolde"]').count();
  console.log(n, "· con partida: insignia", insignia, "· entradas", n1, "· Ysolde visible", y, "· ghul bloqueadas", bloqueadas);
  console.log("   wendigo:", cuerpoW);
  await pg.fill("#bestiario-buscar", "lich"); await pg.waitForTimeout(150);
  const filtrados = await pg.locator("#bestiario-lista details").count();
  const lich = pg.locator('#bestiario-lista details[data-nombre="Lich"]'); await lich.locator("summary").click();
  console.log("   búsqueda «lich»:", filtrados, "· notas:", await lich.locator(".nota-grupo").allInnerTexts());
  await pg.fill("#bestiario-buscar", ""); await pg.selectOption("#bestiario-orden", "menos"); await pg.waitForTimeout(150);
  const primero = await pg.locator("#bestiario-lista details").first().getAttribute("data-nombre");
  console.log("   menos conocidos primero:", primero);
  await pg.keyboard.press("Escape"); await pg.waitForTimeout(150);
  console.log("   Escape cierra:", await pg.evaluate(() => document.getElementById("velo-bestiario").hidden), "· errores:", errs.length, errs.slice(0, 2));
  await abrir(); await pg.locator("#bestiario-buscar").fill(""); 
  await pg.screenshot({ path: salida("bestiario-" + n + ".png") });
  await b.close();
}
